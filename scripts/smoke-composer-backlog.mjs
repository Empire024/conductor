import { _electron as electron, expect } from '@playwright/test'
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import assert from 'node:assert/strict'
const provider = process.argv.includes('--provider=claude') ? 'claude' : 'codex'
const label = provider === 'claude' ? 'Claude' : 'Codex'
const root = await mkdtemp(join(tmpdir(), 'conductor-composer-backlog-'))
const output = resolve('artifacts/composer-backlog', provider)
await mkdir(output, { recursive: true })
const env = { ...process.env, CONDUCTOR_OFFLINE_TESTS: '1', CONDUCTOR_CODEX_EXPERIMENTAL: '1', CONDUCTOR_TEST_EMPTY_HISTORY: '1', CONDUCTOR_TEST_MODEL_CATALOG: '1', CONDUCTOR_TEST_NODE_EXECUTABLE: process.execPath, CONDUCTOR_TEST_USER_DATA: join(root, 'profile'), CONDUCTOR_PROJECTS_ROOT: join(root, 'projects') }
delete env.ELECTRON_RUN_AS_NODE
delete env.CONDUCTOR_LIVE_TESTS
const app = await electron.launch({ args: [resolve('out/main/index.js')], env, timeout: 30000 })
const page = await app.firstWindow()
page.setDefaultTimeout(10000)
const errors = [], checks = []
page.on('pageerror', error => errors.push(error.stack ?? error.message))
const check = name => { checks.push(name); console.log('PASS ' + name) }
const screenshot = async name => { const png = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64')); await writeFile(join(output, name + '.png'), Buffer.from(png, 'base64')) }
try {
  await page.waitForFunction(() => Boolean(window.conductor?.structured))
  const project = await page.evaluate(() => window.conductor.projects.create('Composer backlog'))
  await writeFile(join(project.path, 'alpha.txt'), 'Alpha context')
  await writeFile(join(project.path, 'beta.txt'), 'Beta context')
  await page.reload()
  await page.locator('.project-row').filter({ hasText: 'Composer backlog' }).click()
  await page.locator('.launcher-grid button').filter({ hasText: label }).click()
  const composer = page.getByRole('textbox', { name: provider === 'claude' ? 'Message Claude Code' : 'Message Codex', exact: true })
  await expect(composer).toBeEnabled()
  const id = await page.locator('.structured-agent-pane').getAttribute('data-structured-session')
  await composer.fill('/at')
  await expect(page.getByRole('listbox', { name: 'Chat commands' })).toBeVisible()
  const before = await page.locator('.sa-composer').boundingBox()
  await composer.press('Tab')
  const fileInput = page.getByRole('combobox', { name: 'Context file path', exact: true })
  await expect(fileInput).toBeFocused()
  const during = await page.locator('.sa-composer').boundingBox()
  assert.equal(Math.round(before.height), Math.round(during.height))
  assert.equal(Math.round(before.y), Math.round(during.y))
  const popup = await page.locator('.sa-file-attachment').boundingBox()
  assert.ok(popup.y + popup.height <= during.y)
  await fileInput.fill('alpha')
  await expect(page.getByRole('option', { name: 'alpha.txt', exact: true })).toBeVisible()
  await fileInput.fill('beta')
  await fileInput.press('Enter')
  await expect(page.locator('.sa-context-chips')).toContainText('beta.txt')
  await expect(page.locator('.sa-context-chips')).not.toContainText('alpha.txt')
  await expect(composer).toBeFocused()
  await page.getByRole('button', { name: 'Remove context beta.txt', exact: true }).click()
  await page.getByRole('button', { name: 'Attach file context', exact: true }).click()
  await expect(fileInput).toBeVisible()
  await page.getByRole('button', { name: 'Attach file context', exact: true }).click()
  await expect(fileInput).toHaveCount(0)
  check('Attachment search overlays content, retains geometry, attaches the latest query on Enter, and toggles closed')
  await composer.fill('/pla')
  await expect(page.getByRole('option', { name: /[/]plan/ })).toBeVisible()
  await composer.press('Enter')
  await expect(page.getByRole('button', { name: 'Conversation mode', exact: true })).toContainText('Plan')
  await expect(composer).toHaveValue('')
  const mode = page.getByRole('button', { name: 'Conversation mode', exact: true })
  assert.ok(await mode.locator('svg').first().evaluate(el => el.getBoundingClientRect().width >= 13 && getComputedStyle(el).opacity !== '0'))
  await mode.click()
  const modes = page.getByRole('menu', { name: 'Conversation mode', exact: true })
  assert.ok(await modes.getByRole('menuitemradio').evaluateAll(items => items.every(el => el.querySelector('svg')?.getBoundingClientRect().width >= 14)))
  await screenshot('mode-icons')
  await page.keyboard.press('Escape')
  await composer.fill('/ed')
  await composer.press('Enter')
  await expect(mode).toContainText('Edit')
  if (provider === 'claude') {
    await composer.fill('/fi')
    await expect(page.getByRole('option', { name: /[/]fixture/ })).toBeVisible()
    await composer.press('Tab')
    await expect(composer).toHaveValue('/fixture ')
  }
  await composer.fill('/hist')
  await composer.press('Enter')
  await expect(page.getByRole('dialog', { name: 'Conversation history', exact: true })).toContainText('preview its messages')
  await page.keyboard.press('Escape')
  const initial = await page.evaluate(id => window.conductor.structured.snapshot(id), id)
  assert.equal(initial.items.filter(item => item.data.type === 'text' && item.data.role === 'user').length, 0)
  check('Slash commands select real app actions without submitting prompts; mode icons stay visible and aligned')
  await composer.fill(provider === 'claude' ? 'SYNTHETIC QUESTION' : 'synthetic:question')
  await composer.press('Enter')
  const question = page.locator('.sa-interaction.needs-attention')
  await expect(question).toBeVisible()
  const submit = question.getByRole('button', { name: 'Submit answers', exact: true })
  await expect(submit).toBeDisabled()
  const answer = provider === 'claude' ? question.locator('.sa-custom-answer input') : question.getByRole('radio').first()
  if (provider === 'claude') await answer.fill('Night')
  else await answer.check()
  await expect(submit).toBeEnabled()
  await screenshot('question')
  await answer.press('Enter')
  await expect.poll(async () => (await page.evaluate(id => window.conductor.structured.snapshot(id), id)).phase).toBe('completed')
  await expect(question).toHaveCount(0)
  check('Enter submits both native choices and custom answers through the real provider response path')
  if (provider === 'codex') {
    const paneId = await page.locator('.pane-tab.active').getAttribute('data-control-tab-id')
    const savedId = await page.evaluate(id => window.conductor.structured.fork(id), id)
    await page.evaluate(id => window.conductor.structured.rename(id, 'Saved composer conversation'), savedId)
    await composer.fill('/history'); await composer.press('Enter')
    await page.getByRole('button', { name: /Saved composer conversation/ }).click()
    await expect(page.locator('.sa-history-banner')).toContainText('Previewing saved conversation')
    await expect(composer).toBeDisabled()
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-agent-id', id)
    await screenshot('history-preview')
    await page.getByRole('button', { name: 'Resume this conversation', exact: true }).click()
    await expect(composer).toBeEnabled()
    await expect(page.locator('.sa-history-banner')).toHaveCount(0)
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-tab-id', paneId)
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-agent-id', savedId)
    const persistedResume = await page.evaluate(async projectId => {
      const tabs = node => node.type === 'group' ? node.tabs : node.children.flatMap(tabs)
      return (await window.conductor.sessions.list(projectId)).flatMap(session => tabs(session.layout.root))
    }, project.id)
    assert.equal(persistedResume.find(tab => tab.id === paneId)?.resourceId, savedId)
    assert.ok(!persistedResume.some(tab => tab.resourceId === id))
    check('Saved history previews without retargeting; Resume persists the real native conversation on the same visible tab')
    await composer.fill('synthetic:telemetry'); await composer.press('Enter')
    await expect(page.locator('.sa-timeline')).toContainText('Synthetic telemetry started')
    const timeline = page.locator('.sa-timeline')
    await expect.poll(() => timeline.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThan(5)
    await composer.evaluate(el => { el.style.minHeight = '150px' })
    await expect.poll(() => timeline.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThan(5)
    await writeFile(join(project.path, '.synthetic-telemetry-next'), 'Continue offline fixture')
    await expect(timeline).toContainText('Synthetic telemetry updated')
    await expect.poll(() => timeline.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThan(5)
    await timeline.hover(); await page.mouse.wheel(0, -400)
    await expect.poll(() => timeline.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeGreaterThan(100)
    const top = await timeline.evaluate(el => el.scrollTop)
    await writeFile(join(project.path, '.synthetic-telemetry-finish'), 'Complete offline fixture')
    await expect(page.getByRole('button', { name: /New output/ })).toBeVisible()
    assert.ok(Math.abs(await timeline.evaluate(el => el.scrollTop) - top) < 5)
    await page.getByRole('button', { name: /New output/ }).click()
    await expect(timeline).toContainText('Synthetic telemetry complete')
    await expect.poll(() => timeline.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThan(5)
    check('Streaming and composer resize follow the bottom; deliberate scrolling preserves reading position until Jump to latest')
    await composer.fill('/fork'); await composer.press('Enter')
    await expect.poll(() => page.locator('.structured-agent-pane').getAttribute('data-structured-session')).not.toBe(savedId)
    const forkId = await page.locator('.structured-agent-pane').getAttribute('data-structured-session')
    await expect(composer).toBeEnabled()
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-agent-id', forkId)
    await expect(page.locator('.pane-tab.active')).toContainText('(fork)')
    await page.reload()
    await expect(page.locator('.structured-agent-pane')).toHaveAttribute('data-structured-session', forkId)
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-tab-id', paneId)
    await expect(page.locator('.pane-tab.active')).toHaveAttribute('data-control-agent-id', forkId)
    await expect(composer).toBeEnabled()
    check('Fork persists its new native runtime and title on the same pane and survives renderer reload')
  }
  assert.deepEqual(errors, [])
} catch (error) { await screenshot('failure'); throw error }
finally { await writeFile(join(output, 'results.json'), JSON.stringify({ provider, checks, errors }, null, 2)); await app.close() }

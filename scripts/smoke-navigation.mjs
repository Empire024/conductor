import { _electron as electron, expect } from '@playwright/test'
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import assert from 'node:assert/strict'

const root = await mkdtemp(join(tmpdir(), 'conductor-navigation-'))
const output = resolve('artifacts/navigation')
await mkdir(output, { recursive: true })
const env = { ...process.env, CONDUCTOR_OFFLINE_TESTS: '1', CONDUCTOR_TEST_EMPTY_HISTORY: '1', CONDUCTOR_TEST_MODEL_CATALOG: '1', CONDUCTOR_TEST_NODE_EXECUTABLE: process.execPath, CONDUCTOR_TEST_USER_DATA: join(root, 'profile'), CONDUCTOR_PROJECTS_ROOT: join(root, 'projects') }
delete env.ELECTRON_RUN_AS_NODE
delete env.CONDUCTOR_LIVE_TESTS
const app = await electron.launch({ args: [resolve('out/main/index.js')], env, timeout: 30000 })
const page = await app.firstWindow()
page.setDefaultTimeout(10000)
const errors = [], checks = []
page.on('pageerror', error => errors.push(error.stack ?? error.message))
const pass = name => { checks.push(name); console.log('PASS ' + name) }
const shot = async name => {
  const data = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'))
  await writeFile(join(output, name + '.png'), Buffer.from(data, 'base64'))
}
try {
  await page.waitForFunction(() => Boolean(window.conductor?.agentControl))
  const project = await page.evaluate(() => window.conductor.projects.create('Navigation fixture'))
  await writeFile(join(project.path, 'README.md'), '# Keep my files\n')
  await writeFile(join(project.path, '.env.example'), 'SAFE_FIXTURE=true\n')
  await mkdir(join(project.path, '.config'))
  await writeFile(join(project.path, '.config', 'test.json'), '{}')
  await page.reload()
  await page.locator('.project-row').filter({ hasText: project.name }).click()
  await expect(page.locator('.pane-tab')).toHaveCount(1)
  await page.locator('.pane-add-tab').click()
  await expect(page.locator('.pane-tab')).toHaveCount(2)
  const firstId = await page.locator('.pane-tab').first().getAttribute('data-control-tab-id')
  const secondId = await page.locator('.pane-tab').last().getAttribute('data-control-tab-id')
  await page.locator('.pane-tab').first().click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Close tab', exact: true }).click()
  await expect(page.locator(`[data-control-tab-id="${firstId}"]`)).toHaveCount(0)
  await expect(page.locator(`[data-control-tab-id="${secondId}"]`)).toHaveCount(1)
  pass('Header context menu closes the right-clicked inactive tab')
  const toggle = page.locator('.workspace-tab-toggle').first()
  if (await toggle.getAttribute('aria-expanded') === 'false') await toggle.click()
  await expect(page.locator('.workspace-tab-row')).toHaveCount(1)
  await page.locator('.workspace-tab-row').first().click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Retrieve closed tab', exact: true })).toBeEnabled()
  await page.getByRole('menuitem', { name: 'Retrieve closed tab', exact: true }).click()
  await expect(page.locator('.workspace-tab-row')).toHaveCount(2)
  await expect(page.locator('.pane-tab')).toHaveCount(2)
  await expect(page.locator('.pane-tab.closing')).toHaveCount(0)
  await expect.poll(() => page.locator('.pane-tab').evaluateAll(tabs => tabs.every(tab => tab.getBoundingClientRect().width >= 50))).toBe(true)
  pass('Workspace sidebar lists real tabs and restores closed tabs')
  await page.locator('.workspace-tab-row').first().click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Show tab', exact: true }).click()
  await expect.poll(() => app.windows().length).toBe(2)
  const detached = app.windows().find(window => window !== page)
  await detached.waitForSelector('.pane-tab')
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().filter(window => window.isAlwaysOnTop()).length), 1)
  await expect(page.locator('.pane-tab')).toHaveCount(1)
  await detached.getByRole('button', { name: 'Close', exact: true }).click()
  await expect.poll(() => app.windows().length).toBe(1)
  await expect(page.locator('.pane-tab')).toHaveCount(2)
  pass('Show tab opens a floating window above content and closing it restores the original tab')
  const hoverTab = page.locator('.pane-tab.active')
  await page.locator('.titlebar-brand').hover()
  const beforeHover = await hoverTab.evaluate(element => getComputedStyle(element).backgroundColor)
  await hoverTab.hover()
  await expect.poll(() => hoverTab.evaluate(element => getComputedStyle(element).backgroundColor)).not.toBe(beforeHover)
  const focusedBorder = await page.locator('.pane-group.focused').evaluate(element => ({ border: getComputedStyle(element).borderColor, expected: getComputedStyle(document.documentElement).getPropertyValue('--border').trim(), shadow: getComputedStyle(element).boxShadow }))
  assert.ok(!focusedBorder.shadow.includes('0px 0px 0px 1px'))
  pass('Active tabs have hover feedback and focused panes have no cyan ring')
  await page.getByRole('button', { name: 'Explorer', exact: true }).click()
  const explorer = page.locator(`[data-project-id="${project.id}"]`)
  await expect(explorer.locator('.explorer-dotfile-heading')).toBeVisible()
  const ordered = await explorer.locator('.explorer-row .ellipsis').allTextContents()
  assert.ok(ordered.indexOf('README.md') < ordered.indexOf('.env.example'))
  await explorer.locator('.explorer-row').filter({ hasText: '.config' }).click()
  await expect(explorer.locator('.explorer-row').filter({ hasText: 'test.json' })).toBeVisible()
  pass('Dotfiles and folders remain usable in a separate configuration group')
  await page.locator('.quick-theme-toggle').click({ button: 'right' })
  await page.getByRole('menuitemradio', { name: 'Night', exact: true }).click()
  await page.locator('.quick-theme-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme-variant', 'day')
  const themeControl = await page.locator('.quick-theme-toggle').evaluate(element => ({ height: element.getBoundingClientRect().height, icon: element.querySelector('svg').getBoundingClientRect().width, transition: document.documentElement.classList.contains('theme-changing') }))
  assert.ok(themeControl.height >= 32 && themeControl.icon > 0)
  assert.equal(themeControl.transition, true)
  await expect(page.locator('html')).not.toHaveClass(/theme-changing/)
  await shot('day-explorer')
  pass('Day/night control has visible icons, a full-height click target, and smooth color transitions')
  await page.locator('.activity-rail').getByRole('button', { name: 'Workspace', exact: true }).click()
  await page.locator('.project-row').filter({ hasText: project.name }).click({ button: 'right' })
  await page.getByRole('button', { name: 'Remove from Conductor', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: `Remove ${project.name}?` })
  await expect(dialog).toContainText('Your files stay on disk')
  await expect(dialog.getByRole('button', { name: 'Remove project', exact: true })).toBeVisible()
  await shot('remove-project')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.project-row').filter({ hasText: project.name })).toBeVisible()
  await page.locator('.project-row').filter({ hasText: project.name }).click({ button: 'right' })
  await page.getByRole('button', { name: 'Remove from Conductor', exact: true }).click()
  await page.getByRole('button', { name: 'Remove project', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.project-row').filter({ hasText: project.name })).toHaveCount(0)
  assert.equal(await readFile(join(project.path, 'README.md'), 'utf8'), '# Keep my files\n')
  assert.ok(!(await page.evaluate(() => window.conductor.projects.list())).some(item => item.id === project.id))
  pass('Project removal dialog supports Cancel and removes the registered project while preserving disk files')
  assert.deepEqual(errors, [])
  await writeFile(join(output, 'results.json'), JSON.stringify({ checks, errors }, null, 2))
} finally { await app.close() }
